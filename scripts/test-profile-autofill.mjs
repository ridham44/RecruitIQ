const BASE = 'http://localhost:3001/api/v1';
const ts = Date.now();

async function req(path, { method = 'GET', body, token, isForm = false } = {}) {
  const headers = {};
  if (token) headers.Authorization = `Bearer ${token}`;
  if (!isForm && body) headers['Content-Type'] = 'application/json';
  const res = await fetch(`${BASE}${path}`, { method, headers, body: isForm ? body : body ? JSON.stringify(body) : undefined });
  const json = await res.json().catch(() => null);
  if (!res.ok) {
    console.error(`FAIL ${method} ${path} ->`, res.status, json);
    throw new Error(json?.message || `HTTP ${res.status}`);
  }
  return json.data;
}

function assert(cond, msg) {
  if (!cond) throw new Error('ASSERTION FAILED: ' + msg);
  console.log('  ok:', msg);
}

const email = `autofill-${ts}@test.com`;
const { token } = await req('/auth/register/candidate', {
  method: 'POST',
  body: { email, password: 'password123', fullName: 'Test Candidate' },
});

console.log('== Profile starts with empty academic fields ==');
const { candidate: before } = await req('/candidates/me', { token });
assert(before.university === null, 'university starts empty');
assert(before.degree === null, 'degree starts empty');

console.log('== Upload a resume that mentions university/degree/SPI ==');
// process.argv[2] is a .docx file whose content matches the assertions below
// (generated by the caller via python-docx, since a hand-rolled PDF trips up
// pdf-parse's bundled pdf.js — see earlier session notes).
const docxBuffer = (await import('fs')).readFileSync(process.argv[2]);
const form2 = new FormData();
form2.append(
  'resume',
  new Blob([docxBuffer], { type: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document' }),
  'resume.docx'
);

const { resume, profileSuggestions } = await req('/resumes', { method: 'POST', token, body: form2, isForm: true });
assert(resume.id, 'resume uploaded');
console.log('  profileSuggestions:', JSON.stringify(profileSuggestions));
assert(profileSuggestions !== null, 'profileSuggestions returned (non-null)');

console.log('== Apply suggestions via profile update (simulating review UI accept) ==');
const acceptedPayload = {};
if (profileSuggestions.university) acceptedPayload.university = profileSuggestions.university;
if (profileSuggestions.degree) acceptedPayload.degree = profileSuggestions.degree;
if (profileSuggestions.latestSpi) acceptedPayload.latestSpi = profileSuggestions.latestSpi;

const { candidate: afterSuggest } = await req('/candidates/me', { method: 'PATCH', token, body: acceptedPayload });
console.log('  updated candidate:', JSON.stringify({ university: afterSuggest.university, degree: afterSuggest.degree, latestSpi: afterSuggest.latestSpi }));

console.log('== Manually set a field, then re-upload the SAME resume: must NOT overwrite ==');
await req('/candidates/me', { method: 'PATCH', token, body: { college: 'Manually Entered College' } });

const form3 = new FormData();
form3.append(
  'resume',
  new Blob([docxBuffer], { type: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document' }),
  'resume2.docx'
);
const { profileSuggestions: suggest2 } = await req('/resumes', { method: 'POST', token, body: form3, isForm: true });
console.log('  second upload suggestions:', JSON.stringify(suggest2));
assert(!suggest2 || !('college' in suggest2), 'college is NOT suggested again (already manually set)');

const { candidate: finalCandidate } = await req('/candidates/me', { token });
assert(finalCandidate.college === 'Manually Entered College', 'manually entered college was not overwritten: ' + finalCandidate.college);

console.log('\nALL PROFILE AUTO-FILL TESTS PASSED ✔');
